package com.example.agentic_url_shortener.Entity;

import jakarta.persistence.*;
import java.time.Instant;

@Entity // Maps this class to a relational database table
@Table(name = "short_urls") // Explicit table name in SQL
public class ShortUrl { // Entity representing one shortened link

    @Id // Primary key column
    @GeneratedValue(strategy = GenerationType.IDENTITY) // Auto-incremented ID generated by the database
    private Long id; // Internal surrogate primary key

    @Column(nullable = false, unique = true, length = 16) // Must be present, unique, and max 16 chars
    private String code; // Short lookup key (e.g., "aB3x9Q")

    @Column(nullable = false, length = 2048) // Allows long URLs up to 2048 characters
    private String targetUrl; // Original destination URL

    @Column(nullable = false) // Cannot be null in DB
    private long clickCount; // Tracks how many times the short URL was visited

    @Column(nullable = false) // Cannot be null in DB
    private Instant createdAt; // Timestamp when the short URL was created

    protected ShortUrl() {} // No-arg constructor required by JPA

    public ShortUrl(String code, String targetUrl, Instant createdAt) { // Convenience constructor for new records
        this.code = code; // Assign short code
        this.targetUrl = targetUrl; // Assign target URL
        this.clickCount = 0L; // Start click counter at zero
        this.createdAt = createdAt; // Record creation time
    }

    public Long getId() { return id; } // Getter for primary key
    public String getCode() { return code; } // Getter for short code
    public String getTargetUrl() { return targetUrl; } // Getter for original URL
    public long getClickCount() { return clickCount; } // Getter for click count
    public Instant getCreatedAt() { return createdAt; } // Getter for creation timestamp
    public void incrementClicks() { this.clickCount++; } // Increments click count by 1
}
